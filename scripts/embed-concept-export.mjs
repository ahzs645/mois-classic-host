#!/usr/bin/env node
/* Embed a MOIS Concept Mapping export as the emulator's seed list.
 *
 *   node scripts/embed-concept-export.mjs <concepts.xml | export.7z>
 *
 * Writes src/data/conceptTrainingExport.generated.ts: the export's
 * concepts.xml verbatim, which data/concepts.ts parses at load with
 * data/conceptXml.ts. A 7z is unpacked with the `7z` CLI. */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const input = process.argv[2]
if (!input) { console.error('usage: embed-concept-export.mjs <concepts.xml | export.7z>'); process.exit(1) }

let bytes
if (/\.7z$/i.test(input)) {
  const dir = mkdtempSync(join(tmpdir(), 'concepts-'))
  try {
    execFileSync('7z', ['x', input, `-o${dir}`, '-y', '-p'], { stdio: 'ignore' })
    bytes = readFileSync(join(dir, 'concepts.xml'))
  } finally { rmSync(dir, { recursive: true, force: true }) }
} else {
  bytes = readFileSync(input)
}
const xml = new TextDecoder('iso-8859-1').decode(bytes)
if (!xml.includes('<concepts>') || !xml.includes('nvo_concept_rule')) { console.error(`${input} is not a full Concept Mapping export (concepts.xml)`); process.exit(1) }

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/data/conceptTrainingExport.generated.ts')
writeFileSync(out, `/* GENERATED by scripts/embed-concept-export.mjs from ${basename(input)} — do not edit.
   A MOIS Concept Mapping export's concepts.xml, verbatim. */
export const TRAINING_CONCEPT_XML = ${JSON.stringify(xml)}
`)
console.log(`wrote ${out} (${(xml.match(/<concept>/g) ?? []).length} concepts, ${(xml.match(/<concept_rule>/g) ?? []).length} rules)`)
