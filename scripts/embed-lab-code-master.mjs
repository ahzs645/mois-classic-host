#!/usr/bin/env node
/* Embed the MOIS master lab code list as the emulator's seed.
 *
 *   node scripts/embed-lab-code-master.mjs <measure-catalog.csv[.gz]>
 *
 * The input is the tlp_lab_code catalog export Webforms keeps at
 * data/mois-sql/measure-catalog.csv.gz. MOIS's Advanced Lookup Service ▸
 * Master Lab Code List lists the codes that carry a lab code, in lab-code
 * order: sorting the export's lab-coded rows that way reproduces the
 * 2026-09-29 TRAINING capture's page (WBCONLY … YMWP1) row for row.
 *
 * Writes src/data/labCodeMaster.generated.ts: one tuple per code,
 * [test id, lab code, test name, units, LOINC]. */
import { readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync } from 'node:zlib'

const input = process.argv[2]
if (!input) { console.error('usage: embed-lab-code-master.mjs <measure-catalog.csv[.gz]>'); process.exit(1) }
let bytes = readFileSync(input)
if (/\.gz$/i.test(input)) bytes = gunzipSync(bytes)
const text = bytes.toString('utf8')

/* RFC 4180 rows: quoted fields may hold commas, quotes and newlines. A
   quote anywhere but a field's start is literal (the export has test names
   like ALBERT"S STAIN), the way Python's csv reads it. */
function parse(csv) {
  const rows = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < csv.length; i++) {
    const c = csv[i]
    if (quoted) {
      if (c === '"' && csv[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"' && field === '') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && csv[i + 1] === '\n') i++
      row.push(field); rows.push(row); row = []; field = ''
    } else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  return rows
}

const [head, ...body] = parse(text)
const col = (name) => { const i = head.indexOf(name); if (i < 0) { console.error(`${input} has no ${name} column`); process.exit(1) } return i }
const ID = col('observation_code'), LOINC = col('str_loinic_num'), LAB = col('str_lab_code'), TEST = col('str_test_name'), UNITS = col('str_units')

const rows = body
  .filter((r) => (r[LAB] ?? '').trim())
  .map((r) => [r[ID].replace(/^#/, ''), r[LAB].trim(), (r[TEST] ?? '').trim(), (r[UNITS] ?? '').trim(), (r[LOINC] ?? '').trim()])
  /* code-unit order, the order MOIS lists them in */
  .sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : Number(a[0]) - Number(b[0])))

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/data/labCodeMaster.generated.ts')
writeFileSync(out, `/* GENERATED by scripts/embed-lab-code-master.mjs from ${basename(input)} — do not edit.
   The master lab code list: [test id, lab code, test name, units, LOINC], in lab-code order. */
export const LAB_CODE_MASTER_ROWS: readonly (readonly [string, string, string, string, string])[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
]
`)
console.log(`wrote ${out} (${rows.length} lab codes)`)
