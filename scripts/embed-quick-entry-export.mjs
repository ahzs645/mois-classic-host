#!/usr/bin/env node
/* Embed a MOIS Quick Entry export as the emulator's seed list.
 *
 *   node scripts/embed-quick-entry-export.mjs <quick_entrys.xml | export.7z>
 *
 * Writes src/data/quickEntryTrainingExport.generated.ts: the export's
 * quick_entrys.xml verbatim, which data/quickEntryTemplates.ts parses at
 * load with data/quickEntryXml.ts. A 7z is unpacked with the `7z` CLI. */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const input = process.argv[2]
if (!input) { console.error('usage: embed-quick-entry-export.mjs <quick_entrys.xml | export.7z>'); process.exit(1) }

let bytes
if (/\.7z$/i.test(input)) {
  const dir = mkdtempSync(join(tmpdir(), 'qe-'))
  try {
    execFileSync('7z', ['x', input, `-o${dir}`, '-y', '-p'], { stdio: 'ignore' })
    bytes = readFileSync(join(dir, 'quick_entrys.xml'))
  } finally { rmSync(dir, { recursive: true, force: true }) }
} else {
  bytes = readFileSync(input)
}
const xml = new TextDecoder('iso-8859-1').decode(bytes)
if (!xml.includes('<quick_entrys>')) { console.error(`${input} is not a Quick Entry export`); process.exit(1) }

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/data/quickEntryTrainingExport.generated.ts')
writeFileSync(out, `/* GENERATED by scripts/embed-quick-entry-export.mjs from ${basename(input)} — do not edit.
   A MOIS Quick Entry export's quick_entrys.xml, verbatim. */
export const TRAINING_QUICK_ENTRY_XML = ${JSON.stringify(xml)}
`)
console.log(`wrote ${out} (${(xml.match(/<quick_entry>/g) ?? []).length} templates)`)
